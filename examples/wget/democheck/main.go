// Command democheck asserts the TargetCheck Wget demo matrix from generated
// reports and logs, then writes normalized results so independent runs can be
// compared byte for byte. It is original TargetCheck code (Apache-2.0), run by
// scripts/demo.sh as `go run examples/wget/democheck/main.go`; it reads Wget
// test output but does not contain or link Wget code.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"reflect"
	"runtime"
	"slices"
	"strconv"
	"strings"

	"github.com/firmdura/targetcheck/internal/model"
	"github.com/firmdura/targetcheck/internal/plan"
)

type matrix struct {
	Rows []row `json:"rows"`
}

type row struct {
	Name       string            `json:"name"`
	Matrix     string            `json:"matrix"`
	Claim      string            `json:"claim"`
	Target     string            `json:"target"`
	Baseline   string            `json:"baseline,omitempty"`
	Candidate  string            `json:"candidate,omitempty"`
	ExitCode   int               `json:"exit_code"`
	Outcome    string            `json:"outcome"`
	TestStatus map[string]string `json:"test_status,omitempty"`
	Markers    []marker          `json:"markers,omitempty"`
	SameAs     string            `json:"same_as,omitempty"`
	Differs    string            `json:"differs,omitempty"`
	Failure    *failure          `json:"failure,omitempty"`
}

type marker struct {
	Variant  string `json:"variant"`
	Test     string `json:"test"`
	Stream   string `json:"stream"`
	ExitCode int    `json:"exit_code"`
	Contains string `json:"contains"`
}

type failure struct {
	Kind          string `json:"kind"`
	MessagePrefix string `json:"message_prefix"`
}

// Normalized results omit durations, absolute tool paths and build output,
// which may legitimately differ between fresh runs; everything else is kept.
type normalized struct {
	HostArch string    `json:"host_arch"`
	Rows     []normRow `json:"rows"`
}

type normRow struct {
	Name       string                  `json:"name"`
	CLIExit    int                     `json:"cli_exit"`
	Outcome    model.Outcome           `json:"outcome"`
	Failure    *model.Failure          `json:"failure,omitempty"`
	TargetKind model.TargetKind        `json:"target_kind"`
	Executable string                  `json:"executable,omitempty"`
	Sysroot    string                  `json:"sysroot,omitempty"`
	Manifest   string                  `json:"manifest_sha256"`
	Coverage   []model.VariantCoverage `json:"coverage"`
	Inputs     []model.FileIdentity    `json:"inputs"`
	Variants   []normVariant           `json:"variants"`
}

type normVariant struct {
	Name      string                   `json:"name"`
	CWD       string                   `json:"cwd"`
	Build     []normCheck              `json:"build"`
	Tests     []normCheck              `json:"tests"`
	Artifacts []model.ArtifactIdentity `json:"artifacts"`
}

type normCheck struct {
	ID           string            `json:"id"`
	Status       model.CheckStatus `json:"status"`
	ExitCode     *int              `json:"exit_code,omitempty"`
	StdoutSHA256 string            `json:"stdout_sha256,omitempty"`
	StderrSHA256 string            `json:"stderr_sha256,omitempty"`
}

type checker struct {
	recipe, run string
	reviewed    map[string]string
	errors      []string
	summary     bytes.Buffer
	artifacts   map[string]string // variant/target -> sha256 across rows
	sources     map[string]string // variant -> src/http.c sha256 across rows
}

func (c *checker) fail(format string, args ...any) {
	c.errors = append(c.errors, fmt.Sprintf(format, args...))
}

func main() {
	recipe := flag.String("recipe", "examples/wget", "recipe directory")
	run := flag.String("run", "", "demo run directory")
	out := flag.String("normalized", "", "normalized result output file")
	summary := flag.String("summary", "", "Markdown summary output file")
	flag.Parse()
	if *run == "" || *out == "" || *summary == "" {
		fmt.Fprintln(os.Stderr, "usage: democheck -recipe DIR -run DIR -normalized FILE -summary FILE")
		os.Exit(2)
	}
	c := &checker{recipe: *recipe, run: *run, artifacts: map[string]string{}, sources: map[string]string{}}
	var m matrix
	if err := decodeFile(filepath.Join(*recipe, "matrix.json"), &m); err != nil {
		fatal(err)
	}
	reviewed, err := readSums(filepath.Join(*recipe, "SHA256SUMS"))
	if err != nil {
		fatal(err)
	}
	c.reviewed = reviewed
	result := normalized{HostArch: runtime.GOARCH}
	fmt.Fprintf(&c.summary, "# TargetCheck Wget demo run\n\nHost: linux/%s. Generated by examples/wget/democheck from the reports in this run directory.\n\n", runtime.GOARCH)
	fmt.Fprintf(&c.summary, "| Row | Matrix | Target | Baseline -> candidate | Expected exit | CLI exit | Outcome |\n| --- | --- | --- | --- | --- | --- | --- |\n")
	var details bytes.Buffer
	for _, r := range m.Rows {
		n, rowSummary := c.checkRow(r, m)
		result.Rows = append(result.Rows, n)
		pair := "preflight only"
		if r.Baseline != "" {
			pair = r.Baseline + " -> " + r.Candidate
		}
		fmt.Fprintf(&c.summary, "| %s | %s | %s | %s | %d | %d | %s |\n", r.Name, r.Matrix, r.Target, pair, r.ExitCode, n.CLIExit, n.Outcome)
		details.WriteString(rowSummary)
	}
	// Every executed manifest must be a matrix row; nothing runs unchecked.
	recorded, err := filepath.Glob(filepath.Join(*run, "cli", "*.exit"))
	if err != nil {
		fatal(err)
	}
	if len(recorded) != len(m.Rows) {
		c.fail("run recorded %d CLI invocations, the matrix has %d rows", len(recorded), len(m.Rows))
	}
	c.summary.WriteString("\n")
	c.summary.Write(details.Bytes())
	if len(c.errors) > 0 {
		fmt.Fprintf(os.Stderr, "democheck: %d assertion(s) failed in %s:\n", len(c.errors), *run)
		for _, e := range c.errors {
			fmt.Fprintf(os.Stderr, "  - %s\n", e)
		}
		os.Exit(1)
	}
	data, err := json.MarshalIndent(result, "", "  ")
	if err != nil {
		fatal(err)
	}
	if err = os.WriteFile(*out, append(data, '\n'), 0o644); err != nil {
		fatal(err)
	}
	if err = os.WriteFile(*summary, c.summary.Bytes(), 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("democheck: all %d matrix rows matched their expected exits, outcomes, diagnostics and identities\n", len(m.Rows))
}

func fatal(err error) {
	fmt.Fprintf(os.Stderr, "democheck: %v\n", err)
	os.Exit(2)
}

func decodeFile(path string, v any) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	d := json.NewDecoder(f)
	d.DisallowUnknownFields()
	if err = d.Decode(v); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if d.More() {
		return fmt.Errorf("%s: trailing data", path)
	}
	return nil
}

func readSums(path string) (map[string]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	sums := map[string]string{}
	s := bufio.NewScanner(f)
	for s.Scan() {
		line := s.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 2 || len(fields[0]) != 64 {
			return nil, fmt.Errorf("%s: malformed line %q", path, line)
		}
		sums[fields[1]] = fields[0]
	}
	return sums, s.Err()
}

func sha(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func loadSpec(path string) (model.Spec, []byte, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return model.Spec{}, nil, err
	}
	spec, err := plan.Load(bytes.NewReader(data))
	if err != nil {
		return model.Spec{}, nil, fmt.Errorf("%s: %w", path, err)
	}
	return spec, data, nil
}

func (c *checker) checkRow(r row, m matrix) (normRow, string) {
	n := normRow{Name: r.Name, CLIExit: -1, Inputs: []model.FileIdentity{}, Variants: []normVariant{}, Coverage: []model.VariantCoverage{}}
	var s strings.Builder
	fmt.Fprintf(&s, "## %s (matrix %s)\n\n%s\n\n", r.Name, r.Matrix, r.Claim)
	spec, raw, err := loadSpec(filepath.Join(c.recipe, "manifests", r.Name+".json"))
	if err != nil {
		c.fail("%s: committed manifest: %v", r.Name, err)
		return n, s.String()
	}
	exitText, err := os.ReadFile(filepath.Join(c.run, "cli", r.Name+".exit"))
	if err != nil {
		c.fail("%s: CLI exit was not recorded: %v", r.Name, err)
		return n, s.String()
	}
	if n.CLIExit, err = strconv.Atoi(strings.TrimSpace(string(exitText))); err != nil {
		c.fail("%s: malformed CLI exit record %q", r.Name, exitText)
	}
	if n.CLIExit != r.ExitCode {
		c.fail("%s: CLI exit %d, expected %d", r.Name, n.CLIExit, r.ExitCode)
	}
	cliOut, _ := os.ReadFile(filepath.Join(c.run, "cli", r.Name+".stdout"))
	cliErr, _ := os.ReadFile(filepath.Join(c.run, "cli", r.Name+".stderr"))
	out := filepath.Join(c.run, "reports", r.Name)
	var rep model.Report
	if err = decodeFile(filepath.Join(out, "report.json"), &rep); err != nil {
		c.fail("%s: report.json: %v", r.Name, err)
		return n, s.String()
	}
	if info, err := os.Stat(filepath.Join(out, "report.md")); err != nil || info.Size() == 0 {
		c.fail("%s: report.md is missing or empty", r.Name)
	}
	if _, err := os.Stat(filepath.Join(out, "INCOMPLETE")); err == nil {
		c.fail("%s: output is marked INCOMPLETE", r.Name)
	}
	n.Outcome, n.Failure, n.TargetKind = rep.Outcome, rep.Failure, rep.Target.Kind
	n.Coverage = rep.Declared
	if rep.SchemaVersion != model.SchemaVersion || string(rep.Outcome) != r.Outcome {
		c.fail("%s: report schema %d outcome %q, expected outcome %q", r.Name, rep.SchemaVersion, rep.Outcome, r.Outcome)
	}
	if !strings.Contains(string(cliOut), "targetcheck: "+r.Outcome+"\n") {
		c.fail("%s: CLI summary does not state outcome %q", r.Name, r.Outcome)
	}
	if rep.Target.HostOS != "linux" || rep.Target.HostArch != runtime.GOARCH {
		c.fail("%s: report host %s/%s, expected linux/%s", r.Name, rep.Target.HostOS, rep.Target.HostArch, runtime.GOARCH)
	}
	if r.Failure != nil {
		c.checkPreflightFailure(r, m, spec, rep, string(cliErr))
		if rep.Failure != nil {
			fmt.Fprintf(&s, "CLI exit %d; failure `%s`: %s. Declared coverage and variants are empty: no build or test command ran.\n\n", n.CLIExit, rep.Failure.Kind, rep.Failure.Message)
		}
		return n, s.String()
	}
	if rep.Failure != nil {
		c.fail("%s: unexpected report failure %s: %s", r.Name, rep.Failure.Kind, rep.Failure.Message)
	}
	if rep.Manifest == nil || rep.Manifest.Encoding != "raw_json" || rep.Manifest.SHA256 != sha(raw) {
		c.fail("%s: manifest identity does not match the committed manifest bytes", r.Name)
	} else {
		n.Manifest = rep.Manifest.SHA256
	}
	if string(rep.Target.Kind) != r.Target || rep.Target.Kind != spec.Target.Kind {
		c.fail("%s: target %q, expected %q", r.Name, rep.Target.Kind, r.Target)
	}
	if rep.Target.Kind == model.TargetQEMUARM {
		n.Executable, n.Sysroot = rep.Target.Executable, rep.Target.Sysroot
		want, _ := filepath.EvalSymlinks(spec.Target.Sysroot)
		if !filepath.IsAbs(rep.Target.Executable) || !strings.HasPrefix(filepath.Base(rep.Target.Executable), "qemu-arm") || rep.Target.Sysroot != want {
			c.fail("%s: QEMU target %q sysroot %q does not identify the supplied qemu-arm and %s", r.Name, rep.Target.Executable, rep.Target.Sysroot, want)
		}
	}
	declared := []model.Variant{spec.Variants.Baseline, spec.Variants.Candidate}
	names := []string{r.Baseline, r.Candidate}
	for i, v := range declared {
		if v.CWD != r.Name+"/"+names[i] {
			c.fail("%s: variant cwd %q does not name variant %q", r.Name, v.CWD, names[i])
		}
	}
	var testIDs []string
	for _, t := range spec.Tests {
		testIDs = append(testIDs, t.ID)
	}
	if len(rep.Declared) != 2 || len(rep.Variants) != 2 {
		c.fail("%s: report declares %d variants and contains %d, expected 2", r.Name, len(rep.Declared), len(rep.Variants))
		return n, s.String()
	}
	for i, d := range rep.Declared {
		if want := []model.VariantName{model.Baseline, model.Candidate}[i]; d.Name != want || len(d.BuildIDs) != len(declared[i].Build) || !slices.Equal(d.TestIDs, testIDs) {
			c.fail("%s: declared coverage for %s does not match the manifest", r.Name, want)
		}
	}
	c.checkInputs(r, rep, declared, names)
	n.Inputs = rep.Inputs
	fmt.Fprintf(&s, "CLI exit %d (expected %d), outcome `%s`.\n\n", n.CLIExit, r.ExitCode, rep.Outcome)
	fmt.Fprintf(&s, "| Test | Baseline (%s) | Candidate (%s) |\n| --- | --- | --- |\n", r.Baseline, r.Candidate)
	rowsByTest := map[string][2]string{}
	var diag strings.Builder
	for i, v := range rep.Variants {
		nv := c.checkVariant(r, spec, rep, declared[i], names[i], v, out, rowsByTest, i, &diag)
		n.Variants = append(n.Variants, nv)
	}
	for _, id := range testIDs {
		cells := rowsByTest[id]
		fmt.Fprintf(&s, "| %s | %s | %s |\n", id, cells[0], cells[1])
	}
	s.WriteString("\n")
	if diag.Len() > 0 {
		s.WriteString("Named diagnostics observed in the persisted logs:\n\n")
		s.WriteString(diag.String())
		s.WriteString("\n")
	}
	s.WriteString("| Variant | Artifact | SHA-256 | ELF |\n| --- | --- | --- | --- |\n")
	for _, v := range rep.Variants {
		for _, a := range v.ArtifactsAfter {
			fmt.Fprintf(&s, "| %s | %s | %s | %s %s %s %s |\n", v.Name, a.Path, a.SHA256, a.ELF.Class, a.ELF.Machine, a.ELF.Endian, a.ELF.ABI)
		}
	}
	s.WriteString("\n")
	return n, s.String()
}

// checkPreflightFailure requires the manifest to be the referenced positive
// manifest except for one target field, and the report to contain no checks.
func (c *checker) checkPreflightFailure(r row, m matrix, spec model.Spec, rep model.Report, cliErr string) {
	if rep.Failure == nil || string(rep.Failure.Kind) != r.Failure.Kind || !strings.HasPrefix(rep.Failure.Message, r.Failure.MessagePrefix) {
		c.fail("%s: failure %+v, expected kind %s with message %q", r.Name, rep.Failure, r.Failure.Kind, r.Failure.MessagePrefix)
		return
	}
	if !strings.Contains(cliErr, r.Failure.MessagePrefix) {
		c.fail("%s: CLI stderr does not name the failure %q", r.Name, r.Failure.MessagePrefix)
	}
	if len(rep.Declared) != 0 || len(rep.Variants) != 0 || rep.Manifest != nil || len(rep.Inputs) != 0 {
		c.fail("%s: a preflight failure report must not contain coverage, variants or identities", r.Name)
	}
	base, _, err := loadSpec(filepath.Join(c.recipe, "manifests", r.SameAs+".json"))
	if err != nil {
		c.fail("%s: %v", r.Name, err)
		return
	}
	changed := spec
	switch r.Differs {
	case "executable":
		if spec.Target.Executable == base.Target.Executable {
			c.fail("%s: executable is not changed", r.Name)
		}
		changed.Target.Executable = base.Target.Executable
	case "sysroot":
		if spec.Target.Sysroot == base.Target.Sysroot {
			c.fail("%s: sysroot is not changed", r.Name)
		}
		changed.Target.Sysroot = base.Target.Sysroot
	default:
		c.fail("%s: unsupported differs %q", r.Name, r.Differs)
	}
	changed.ManifestJSON, base.ManifestJSON = nil, nil
	if !reflect.DeepEqual(changed, base) {
		c.fail("%s: manifest differs from %s in more than target %s", r.Name, r.SameAs, r.Differs)
	}
	found := false
	for _, other := range m.Rows {
		found = found || other.Name == r.SameAs
	}
	if !found {
		c.fail("%s: same_as row %s is not part of the matrix", r.Name, r.SameAs)
	}
}

// checkInputs binds every declared variant input to the reviewed variant
// sources, so the same instrumentation is proven identical across variants.
func (c *checker) checkInputs(r row, rep model.Report, declared []model.Variant, names []string) {
	byPath := map[string]model.FileIdentity{}
	for _, in := range rep.Inputs {
		byPath[in.Path] = in
	}
	want := 0
	for i, v := range declared {
		for _, p := range v.Inputs {
			want++
			in, ok := byPath[v.CWD+"/"+p]
			if !ok {
				c.fail("%s: declared input %s/%s has no identity", r.Name, v.CWD, p)
				continue
			}
			data, err := os.ReadFile(filepath.Join(c.run, "root", v.CWD, p))
			if err != nil || sha(data) != in.SHA256 || int64(len(data)) != in.SizeBytes {
				c.fail("%s: input %s does not match its recorded identity", r.Name, in.Path)
			}
			if expected, ok := c.reviewed[names[i]+"/"+p]; ok && expected != in.SHA256 {
				c.fail("%s: %s has SHA-256 %s, reviewed %s is %s", r.Name, in.Path, in.SHA256, names[i], expected)
			}
			if p == "TARGETCHECK-VARIANT.txt" && !bytes.HasPrefix(data, []byte("TargetCheck Wget example variant: "+names[i]+"\n")) {
				c.fail("%s: %s does not describe variant %s", r.Name, in.Path, names[i])
			}
			if p == "src/http.c" {
				if prior, ok := c.sources[names[i]]; ok && prior != in.SHA256 {
					c.fail("%s: %s source differs from another row", r.Name, names[i])
				}
				c.sources[names[i]] = in.SHA256
			}
		}
	}
	if len(rep.Inputs) != want {
		c.fail("%s: report has %d input identities, expected %d", r.Name, len(rep.Inputs), want)
	}
	for _, p := range []string{"configure", "tests/content-range-cases.c", "tests/unit-tests.c", "tests/unit-tests.h"} {
		a, b := byPath[declared[0].CWD+"/"+p], byPath[declared[1].CWD+"/"+p]
		if a.SHA256 == "" || a.SHA256 != b.SHA256 {
			c.fail("%s: %s differs between baseline and candidate; instrumentation must be identical", r.Name, p)
		}
	}
	if names[0] != names[1] && byPath[declared[0].CWD+"/src/http.c"].SHA256 == byPath[declared[1].CWD+"/src/http.c"].SHA256 {
		c.fail("%s: baseline and candidate src/http.c are identical", r.Name)
	}
}

func (c *checker) checkVariant(r row, spec model.Spec, rep model.Report, declared model.Variant, name string, v model.VariantReport, out string, cells map[string][2]string, index int, diag *strings.Builder) normVariant {
	nv := normVariant{Name: string(v.Name), CWD: v.CWD, Build: []normCheck{}, Tests: []normCheck{}, Artifacts: v.ArtifactsAfter}
	label := fmt.Sprintf("%s %s", r.Name, v.Name)
	if v.CWD != declared.CWD {
		c.fail("%s: cwd %q, expected %q", label, v.CWD, declared.CWD)
	}
	if len(v.Build) != len(declared.Build) {
		c.fail("%s: %d build checks, expected %d", label, len(v.Build), len(declared.Build))
	}
	for i, b := range v.Build {
		nb := normCheck{ID: b.ID, Status: b.Status}
		if b.Observation != nil {
			nb.ExitCode = b.Observation.ExitCode
		}
		if b.Status != model.CheckMatched || b.Observation == nil || b.Observation.ExitCode == nil || *b.Observation.ExitCode != 0 {
			c.fail("%s: build %s did not succeed (%s: %s)", label, b.ID, b.Status, b.Reason)
		} else if i < len(declared.Build) && !slices.Equal(b.Observation.Argv, declared.Build[i].Argv) {
			c.fail("%s: build %s argv %q differs from the manifest", label, b.ID, b.Observation.Argv)
		}
		nv.Build = append(nv.Build, nb)
	}
	bits := 64
	if rep.Target.Kind == model.TargetQEMUARM {
		bits = 32
	}
	sizes := fmt.Sprintf("TYPE SIZES: long=%d bits, wgint=64 bits", bits)
	wantStatus := model.CheckStatus(r.TestStatus[string(v.Name)])
	if len(v.Tests) != len(spec.Tests) {
		c.fail("%s: %d tests, expected %d", label, len(v.Tests), len(spec.Tests))
	}
	for i, t := range v.Tests {
		nt := normCheck{ID: t.ID, Status: t.Status}
		if i >= len(spec.Tests) || t.ID != spec.Tests[i].ID {
			c.fail("%s: test %d is %q, out of manifest order", label, i, t.ID)
			continue
		}
		o := t.Observation
		if o == nil || !o.Started || o.ExitCode == nil || o.Failure != nil || o.Signal != "" {
			c.fail("%s: test %s has no normal process observation (%s: %s)", label, t.ID, t.Status, t.Reason)
			nv.Tests = append(nv.Tests, nt)
			continue
		}
		nt.ExitCode = o.ExitCode
		if t.Status != wantStatus {
			c.fail("%s: test %s is %s (exit %d), expected %s", label, t.ID, t.Status, *o.ExitCode, wantStatus)
		}
		wantArgv := []string{"./tests/unit-tests", t.ID}
		if rep.Target.Kind == model.TargetQEMUARM {
			wantArgv = append([]string{rep.Target.Executable, "-L", rep.Target.Sysroot}, wantArgv...)
		}
		if !slices.Equal(o.Argv, wantArgv) {
			c.fail("%s: test %s argv %q, expected %q", label, t.ID, o.Argv, wantArgv)
		}
		stdout := c.readLog(label, t.ID, out, o.Stdout)
		stderr := c.readLog(label, t.ID, out, o.Stderr)
		nt.StdoutSHA256, nt.StderrSHA256 = sha(stdout), sha(stderr)
		if !bytes.Contains(stdout, []byte(sizes)) {
			c.fail("%s: test %s did not report %q", label, t.ID, sizes)
		}
		ub := bytes.Contains(stderr, []byte("runtime error:"))
		if ub && (v.Name == model.Candidate || *o.ExitCode == 0) {
			c.fail("%s: test %s reported undefined behavior", label, t.ID)
		}
		e := t.Expectation
		if t.Status == model.CheckMatched {
			if !bytes.Contains(stdout, []byte(e.StdoutContains)) || !bytes.Contains(stderr, []byte(e.StderrContains)) || *o.ExitCode != e.ExitCode {
				c.fail("%s: matched test %s does not show its expectation in the logs", label, t.ID)
			}
			if e.ExitCode == 0 && !bytes.Contains(stdout, []byte("PASSED "+t.ID+"\n")) {
				c.fail("%s: passing test %s did not report PASSED", label, t.ID)
			}
		}
		explained := t.Status == model.CheckMatched
		for _, mk := range r.Markers {
			if mk.Variant != string(v.Name) || mk.Test != t.ID {
				continue
			}
			log := stdout
			if mk.Stream == "stderr" {
				log = stderr
			}
			line := lineWith(log, mk.Contains)
			if line == "" || *o.ExitCode != mk.ExitCode {
				c.fail("%s: test %s lacks named diagnostic %q with exit %d (observed exit %d)", label, t.ID, mk.Contains, mk.ExitCode, *o.ExitCode)
				continue
			}
			// A named assertion failure must not be undefined behavior too.
			if mk.Stream == "stdout" && ub {
				c.fail("%s: test %s failed its assertion and reported undefined behavior", label, t.ID)
			}
			explained = true
			fmt.Fprintf(diag, "- %s `%s` (%s, exit %d): `%s`\n", v.Name, t.ID, mk.Stream, *o.ExitCode, line)
		}
		if !explained {
			c.fail("%s: test %s mismatched without a named expected diagnostic", label, t.ID)
		}
		cell := cells[t.ID]
		cell[index] = fmt.Sprintf("%s (exit %d)", t.Status, *o.ExitCode)
		cells[t.ID] = cell
		nv.Tests = append(nv.Tests, nt)
	}
	if !reflect.DeepEqual(v.ArtifactsBefore, v.ArtifactsAfter) || len(v.ArtifactsAfter) != 1 {
		c.fail("%s: artifact identities changed or are incomplete", label)
		return nv
	}
	a := v.ArtifactsAfter[0]
	want := model.ELFIdentity{Class: "ELF32", Machine: "EM_ARM", Endian: "little", ABI: "arm-eabi5-hard-float"}
	if rep.Target.Kind == model.TargetNative {
		want = model.ELFIdentity{Class: "ELF64", Machine: map[string]string{"amd64": "EM_X86_64", "arm64": "EM_AARCH64"}[runtime.GOARCH], Endian: "little", ABI: "linux-" + runtime.GOARCH}
	}
	if a.Path != declared.CWD+"/tests/unit-tests" || a.ELF != want {
		c.fail("%s: artifact %s ELF %+v, expected %+v", label, a.Path, a.ELF, want)
	}
	key := name + "/" + string(rep.Target.Kind)
	if prior, ok := c.artifacts[key]; ok && prior != a.SHA256 {
		c.fail("%s: %s artifact %s differs from the same variant built in another row (%s)", label, key, a.SHA256, prior)
	}
	c.artifacts[key] = a.SHA256
	return nv
}

func (c *checker) readLog(label, id, out string, capture model.Capture) []byte {
	if capture.Log == "" || capture.Truncated {
		c.fail("%s: test %s capture has no complete log", label, id)
		return nil
	}
	f, err := os.Open(filepath.Join(out, filepath.FromSlash(capture.Log)))
	if err != nil {
		c.fail("%s: test %s log: %v", label, id, err)
		return nil
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, model.MaxCaptureBytes+1))
	if err != nil || int64(len(data)) != capture.Bytes {
		c.fail("%s: test %s log %s has %d bytes, report records %d", label, id, capture.Log, len(data), capture.Bytes)
	}
	return data
}

func lineWith(data []byte, needle string) string {
	for _, line := range strings.Split(string(data), "\n") {
		if strings.Contains(line, needle) {
			return line
		}
	}
	return ""
}
